/**
 * Setup .env file script
 * This script helps create the .env file with proper MongoDB configuration
 */

const fs = require('fs');
const path = require('path');
const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

const envPath = path.join(__dirname, '.env');

function question(query) {
  return new Promise(resolve => rl.question(query, resolve));
}

async function setup() {
  console.log('\n🔧 MongoDB Environment Setup\n');
  console.log('This script will help you create the .env file for MongoDB connection.\n');

  // Check if .env already exists
  if (fs.existsSync(envPath)) {
    const overwrite = await question('⚠️  .env file already exists. Overwrite? (y/N): ');
    if (overwrite.toLowerCase() !== 'y') {
      console.log('❌ Setup cancelled. Existing .env file preserved.');
      rl.close();
      return;
    }
  }

  // Choose MongoDB option
  console.log('\nChoose MongoDB option:');
  console.log('1. Local MongoDB (mongodb://localhost:27017)');
  console.log('2. MongoDB Atlas (Cloud)');
  const option = await question('\nEnter option (1 or 2): ');

  let mongoURI = '';

  if (option === '1') {
    // Local MongoDB
    mongoURI = 'mongodb://localhost:27017/medicare';
    console.log('\n✅ Using local MongoDB');
    console.log('   Make sure MongoDB is installed and running on your machine.');
  } else if (option === '2') {
    // MongoDB Atlas
    console.log('\n📝 MongoDB Atlas Setup:');
    console.log('   1. Go to https://www.mongodb.com/cloud/atlas');
    console.log('   2. Create a cluster (free tier available)');
    console.log('   3. Create a database user');
    console.log('   4. Add your IP to Network Access');
    console.log('   5. Get connection string from "Connect" → "Connect your application"\n');
    
    const username = await question('Enter MongoDB Atlas username: ');
    const password = await question('Enter MongoDB Atlas password: ');
    const cluster = await question('Enter cluster name (e.g., cluster0.xxxxx): ');
    
    mongoURI = `mongodb+srv://${username}:${password}@${cluster}/medicare?retryWrites=true&w=majority`;
    console.log('\n✅ Using MongoDB Atlas');
  } else {
    console.log('❌ Invalid option. Setup cancelled.');
    rl.close();
    return;
  }

  // Generate JWT secret
  const jwtSecret = require('crypto').randomBytes(32).toString('hex');

  // Create .env content
  const envContent = `# Environment Variables
# Generated by setup-env.js
# DO NOT commit this file to Git

# Server Configuration
PORT=5000
NODE_ENV=development
FRONTEND_URL=http://localhost:8080

# MongoDB Configuration
MONGODB_URI=${mongoURI}

# JWT Configuration
JWT_SECRET=${jwtSecret}
JWT_EXPIRE=7d

# Other Configuration
BCRYPT_ROUNDS=10
`;

  // Write .env file
  try {
    fs.writeFileSync(envPath, envContent);
    console.log('\n✅ .env file created successfully!');
    console.log(`   Location: ${envPath}`);
    console.log('\n📋 Summary:');
    console.log(`   MongoDB URI: ${mongoURI.replace(/:[^:@]+@/, ':****@')}`); // Hide password
    console.log(`   JWT Secret: Generated (${jwtSecret.length} characters)`);
    console.log('\n🚀 Next steps:');
    console.log('   1. Restart your backend server: npm run dev');
    console.log('   2. Check for "✅ MongoDB Connected" message');
    console.log('\n⚠️  Important:');
    console.log('   - .env file is gitignored (not tracked by Git)');
    console.log('   - Keep your credentials secure');
    console.log('   - Never commit .env file to version control\n');
  } catch (error) {
    console.error('❌ Error creating .env file:', error.message);
  }

  rl.close();
}

setup().catch(error => {
  console.error('❌ Setup error:', error);
  rl.close();
  process.exit(1);
});

